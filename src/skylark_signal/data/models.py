from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field
from skylark_signal.data.quality import QualityFlag

class CanonicalDealRecord(BaseModel):
    """Canonical model for a Deals record."""
    source_system: str = Field("Excel", description="Source system identifier")
    source_file: str = Field(..., description="Source filename")
    source_sheet: str = Field(..., description="Worksheet name")
    source_row_number: int = Field(..., description="Original Excel row index")
    source_record_id: str = Field(..., description="Deterministic row hash identifier")
    deal_id: str = Field(..., description="Surrogate import identifier e.g. IMPORT-DEAL-XXXXXXXX")
    deal_name: str = Field(..., description="Cleaned deal name / generic alias")
    customer: str = Field(..., description="Normalized customer account code e.g. COMPANY_005")
    sector: Optional[str] = Field(None, description="Mapped industry sector")
    stage: str = Field(..., description="Mapped pipeline stage")
    status: str = Field(..., description="Mapped high-level deal status (Won, Dead, Open, On Hold)")
    deal_value: Optional[float] = Field(None, description="Numeric deal monetary value")
    probability: Optional[float] = Field(None, description="Win probability decimal 0.0 - 1.0")
    expected_close_date: Optional[str] = Field(None, description="ISO 8601 target close date YYYY-MM-DD")
    expected_close_period: Optional[str] = Field(None, description="Financial period string e.g. Q3 FY26")
    actual_close_date: Optional[str] = Field(None, description="ISO 8601 actual close date YYYY-MM-DD")
    owner: Optional[str] = Field(None, description="Account owner / KAM code")
    created_date: Optional[str] = Field(None, description="ISO 8601 creation date YYYY-MM-DD")
    product_or_service: Optional[str] = Field(None, description="Product / service category")
    raw_values: Dict[str, Any] = Field(default_factory=dict, description="Original unparsed string row dictionary")
    quality_flags: List[QualityFlag] = Field(default_factory=list, description="Structured quality flags")
    excluded_from_metrics: bool = Field(False, description="Flag indicating exclusion from BI metrics")
    exclusion_reasons: List[str] = Field(default_factory=list, description="List of metric exclusion reasons")

class CanonicalWorkOrderRecord(BaseModel):
    """Canonical model for a Work Order record."""
    source_system: str = Field("Excel", description="Source system identifier")
    source_file: str = Field(..., description="Source filename")
    source_sheet: str = Field(..., description="Worksheet name")
    source_row_number: int = Field(..., description="Original Excel row index")
    source_record_id: str = Field(..., description="Deterministic row hash identifier")
    work_order_id: str = Field(..., description="Canonical work order identifier (Serial #)")
    work_order_name: str = Field(..., description="Cleaned work order name")
    deal_reference: Optional[str] = Field(None, description="Reference deal ID (remains None unless source verified)")
    customer: str = Field(..., description="Normalized customer account code e.g. COMPANY_005")
    sector: Optional[str] = Field(None, description="Mapped industry sector")
    nature_of_work: Optional[str] = Field(None, description="Contract / engagement nature")
    project_value_excl_tax: Optional[float] = Field(None, description="Project contract value excluding tax")
    project_value_incl_tax: Optional[float] = Field(None, description="Project contract value including tax")
    implied_tax_rate: Optional[float] = Field(None, description="Calculated implied tax rate decimal e.g. 0.18")
    start_date: Optional[str] = Field(None, description="ISO 8601 start date YYYY-MM-DD")
    due_date: Optional[str] = Field(None, description="ISO 8601 end / due date YYYY-MM-DD")
    completion_date: Optional[str] = Field(None, description="ISO 8601 data delivery date YYYY-MM-DD")
    execution_status: str = Field(..., description="Mapped execution status")
    invoice_status: Optional[str] = Field(None, description="Mapped invoice status")
    billing_status: Optional[str] = Field(None, description="Mapped billing status")
    progress: Optional[float] = Field(None, description="Execution progress percentage")
    owner: Optional[str] = Field(None, description="BD/KAM personnel code")
    location: Optional[str] = Field(None, description="Project location / region")
    raw_values: Dict[str, Any] = Field(default_factory=dict, description="Original unparsed string row dictionary")
    quality_flags: List[QualityFlag] = Field(default_factory=list, description="Structured quality flags")
    excluded_from_metrics: bool = Field(False, description="Flag indicating exclusion from BI metrics")
    exclusion_reasons: List[str] = Field(default_factory=list, description="List of metric exclusion reasons")
